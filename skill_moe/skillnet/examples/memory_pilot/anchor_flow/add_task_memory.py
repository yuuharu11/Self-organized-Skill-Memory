#!/usr/bin/env python3
"""Append one task's same-interval key/value rows to a frozen S2 M6 memory."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

try:
    from .memory import backbone_digest, load_memory, save_memory, validate_key_text_source
except ImportError:  # Allow direct execution as a script from this directory.
    from memory import backbone_digest, load_memory, save_memory, validate_key_text_source


def append_task(memory, data):
    required = ("actions", "state", "key", "episode_id", "init_state_id", "task", "suite", "normalization_sha256")
    missing = [name for name in required if name not in data]
    if missing:
        raise ValueError(f"addition cache missing fields: {missing}")
    actions = np.asarray(data["actions"], np.float32)
    states = np.asarray(data["state"], np.float32)
    keys = np.asarray(data["key"], np.float32)
    episodes = np.asarray(data["episode_id"]).astype(str)
    initials = np.asarray(data["init_state_id"]).astype(str)
    tasks = np.asarray(data["task"]).astype(str)
    n = len(actions)
    if actions.shape != (n, 10, 32) or states.shape != (n, 32) or len(keys) != n:
        raise ValueError("task rows must use the frozen [10,32] action and [N,32] state convention")
    if not all(len(np.asarray(data[name])) == n for name in ("episode_id", "init_state_id", "task")):
        raise ValueError("task metadata lengths must match actions")
    if not np.all(np.isin(np.asarray(data["suite"]).astype(str), ["libero10", "libero_skill"])):
        raise ValueError("only LIBERO-10 or LIBERO-Skill experience may be appended after LIBERO-90")
    text_source = validate_key_text_source(data)
    if text_source != getattr(memory, "key_text_source", None):
        raise ValueError("addition key text source differs from the LIBERO-90 memory key source")
    if text_source == "pi05_generated_subtask":
        incoming_generator = str(Path(str(np.asarray(data["key_text_generator_checkpoint"]).item())).resolve())
        stored_generator = getattr(memory, "key_text_generator_checkpoint", "")
        if incoming_generator != stored_generator:
            raise ValueError("addition keys were generated by a different π0.5 checkpoint than the memory")
    norm_hash = str(np.asarray(data["normalization_sha256"]).item())
    if norm_hash != getattr(memory, "normalization_sha256", None):
        raise ValueError("addition data normalization does not match the frozen LIBERO-90 codec")
    bases, _ = memory.encode(actions, states)
    before = backbone_digest(memory)
    units_before = len(memory._centers)
    results = []
    for i in range(n):
        results.append(memory.memory_add(keys[i], bases[i], {
            "episode_id": episodes[i], "init_state_id": initials[i],
            "task": tasks[i], "suite": str(np.asarray(data.get("suite", ["unknown"] * n))[i]),
            "raw_action": actions[i].copy(),
            "seed": False,
        }))
    after = backbone_digest(memory)
    if before != after:
        raise AssertionError("memory addition updated M1 encoder/decoder/prior weights")
    return {"rows": n, "added": sum(bool(row["added"]) for row in results),
            "key_only_or_unassigned": sum(row.get("unit_id") is None for row in results),
            "units_before": units_before, "units_after": len(memory._centers),
            "weights_sha256_before": before, "weights_sha256_after": after,
            "results": results}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--memory", required=True)
    parser.add_argument("--task-npz", required=True)
    parser.add_argument("--output-memory", required=True)
    parser.add_argument("--report", required=True)
    args = parser.parse_args()
    output = Path(args.output_memory)
    report_path = Path(args.report)
    if output.exists() or report_path.exists():
        raise FileExistsError("output memory and report paths must be new")
    with np.load(args.task_npz, allow_pickle=True) as archive:
        data = {name: archive[name] for name in archive.files}
    memory = load_memory(args.memory)
    report = append_task(memory, data)
    save_memory(memory, output)
    report["input_memory"] = str(Path(args.memory).resolve())
    report["output_memory"] = str(output.resolve())
    report["task_npz"] = str(Path(args.task_npz).resolve())
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, indent=2) + "\n")
    print({key: report[key] for key in ("rows", "added", "key_only_or_unassigned", "weights_sha256_before",
                                       "weights_sha256_after", "output_memory")})


if __name__ == "__main__":
    main()
